/**
 * Turns the type icons in assets/type-icons/*.svg into
 * src/generated/type-icons.ts, a map from type to SVG markup that
 * react-native-svg's <SvgXml> can draw.
 *
 *   npm run icons
 *
 * The icons are white glyphs; their fills become "currentColor", so the app
 * picks the glyph colour (white or dark, depending on the type colour).
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import { TYPES } from "../../src/db/schema";

const ICONS = path.resolve("assets/type-icons");
const GENERATED = path.resolve("src/generated/type-icons.ts");

/** Recolours the glyph and drops the fixed 512px size (the viewBox stays). */
export function toTemplate(svg: string): string {
  return svg
    .replace(/fill="(white|#fff|#ffffff)"/gi, 'fill="currentColor"')
    .replace(/\s(width|height)="\d+"/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function main() {
  // "???" (the Curse move's type) has no icon.
  const types = TYPES.filter((t) => t !== "???");
  const entries = types.map((type) => {
    const svg = readFileSync(path.join(ICONS, `${type}.svg`), "utf8");
    return `  ${type}: ${JSON.stringify(toTemplate(svg))},`;
  });
  const source = `// Generated by scripts/icons/build-type-icons.ts. Do not edit.
import type { PokemonType } from "@/db/schema";

export const typeIcons: Partial<Record<PokemonType, string>> = {
${entries.join("\n")}
};
`;
  mkdirSync(path.dirname(GENERATED), { recursive: true });
  writeFileSync(GENERATED, source);
  console.log(`✓ Wrote ${types.length} type icons`);
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === path.resolve(__filename)
)
  main();
