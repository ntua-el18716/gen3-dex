/**
 * Picks each Pokémon's two main colours from its front sprite and writes
 * src/generated/sprite-colors.ts (dex number → two hex colours), for
 * backgrounds tinted like the Pokémon itself instead of its type.
 *
 *   npm run sprite-colors   (reads assets/sprites/front, so after npm run sprites)
 *
 * A Gen 3 sprite has 15 colours, mostly a few hues in three or four shades
 * each. Shades of one hue are grouped; a group's weight is how many pixels
 * it covers, favouring vivid colours over greys, and ignoring the outline
 * and highlights. The heaviest group is the main colour, the heaviest one
 * with a clearly different hue the second (or the main again if the
 * Pokémon is all one colour).
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import { readIndices } from "./build-sprites";

const SPRITES = path.resolve("assets/sprites/front");
const GENERATED = path.resolve("src/generated/sprite-colors.ts");

type Rgb = [number, number, number];
type Shade = { rgb: Rgb; count: number };

/** Hue in degrees, saturation and lightness in 0–1. */
export function toHsl([r, g, b]: Rgb): [number, number, number] {
  const max = Math.max(r, g, b) / 255;
  const min = Math.min(r, g, b) / 255;
  const l = (max + min) / 2;
  const d = max - min;
  if (d === 0) return [0, 0, l];
  const s = d / (1 - Math.abs(2 * l - 1));
  const [rn, gn, bn] = [r / 255, g / 255, b / 255];
  const h =
    max === rn
      ? ((gn - bn) / d + 6) % 6
      : max === gn
        ? (bn - rn) / d + 2
        : (rn - gn) / d + 4;
  return [h * 60, s, l];
}

function hueDistance(a: number, b: number) {
  const d = Math.abs(a - b) % 360;
  return d > 180 ? 360 - d : d;
}

const hex = (rgb: Rgb) =>
  "#" + rgb.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("");

/** Shades closer than this in hue belong to one colour. */
const SAME_HUE = 35;
/** The second colour must differ from the first by at least this. */
const OTHER_HUE = 40;

/**
 * The two main colours among `shades` (palette colours with pixel counts).
 * Greys count only when nothing vivid is left (Aron, Magnemite…).
 */
export function mainColours(shades: Shade[]): [string, string] {
  const usable = shades.filter(({ rgb }) => {
    const [, , l] = toHsl(rgb);
    return l > 0.16 && l < 0.92; // not outline, not highlight
  });
  type Group = { hue: number; grey: boolean; weight: number; shades: Shade[] };
  const groups: Group[] = [];
  for (const shade of usable) {
    const [h, s] = toHsl(shade.rgb);
    const grey = s < 0.12;
    const weight = shade.count * (grey ? 0.5 : 0.7 + 0.5 * s);
    const group = groups.find(
      (g) => g.grey === grey && (grey || hueDistance(g.hue, h) < SAME_HUE),
    );
    if (group) {
      group.weight += weight;
      group.shades.push(shade);
    } else groups.push({ hue: h, grey, weight, shades: [shade] });
  }
  if (groups.length === 0) return ["#9ca3af", "#9ca3af"];
  groups.sort((a, b) => b.weight - a.weight);

  /** A group's colour: its shades averaged by how much of the sprite they cover. */
  const colour = (g: Group): string => {
    const total = g.shades.reduce((sum, s) => sum + s.count, 0);
    return hex(
      [0, 1, 2].map(
        (i) =>
          g.shades.reduce((sum, s) => sum + s.rgb[i]! * s.count, 0) / total,
      ) as Rgb,
    );
  };
  const first = groups[0]!;
  const second =
    groups.find(
      (g) =>
        g !== first &&
        g.weight > first.weight * 0.12 &&
        (g.grey !== first.grey || hueDistance(g.hue, first.hue) >= OTHER_HUE),
    ) ?? first;
  return [colour(first), colour(second)];
}

/** Palette colours of an indexed PNG with how many pixels use each. */
export function spriteShades(png: Buffer): Shade[] {
  const { chunks, indices } = readIndices(png);
  const palette = chunks.find((c) => c.type === "PLTE")!.data;
  const alpha = chunks.find((c) => c.type === "tRNS")?.data;
  const counts = new Map<number, number>();
  for (const i of indices) counts.set(i, (counts.get(i) ?? 0) + 1);
  return [...counts]
    .filter(([i]) => (alpha?.[i] ?? 255) > 0)
    .map(([i, count]) => ({
      rgb: [palette[i * 3]!, palette[i * 3 + 1]!, palette[i * 3 + 2]!],
      count,
    }));
}

function main() {
  const ids = readdirSync(SPRITES)
    .map((f) => Number.parseInt(f, 10))
    .filter(Number.isFinite)
    .sort((a, b) => a - b);
  const lines = ids.map((id) => {
    const [a, b] = mainColours(
      spriteShades(readFileSync(path.join(SPRITES, `${id}.png`))),
    );
    return `  ${id}: ["${a}", "${b}"],`;
  });
  writeFileSync(
    GENERATED,
    `// Generated by scripts/sprites/build-sprite-colors.ts. Do not edit.\n` +
      `/** Each Pokémon's two main colours, taken from its sprite. */\n` +
      `export const spriteColors: Record<number, readonly [string, string]> = {\n` +
      `${lines.join("\n")}\n};\n`,
  );
  console.log(`Wrote colours for ${ids.length} sprites.`);
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === path.resolve(__filename)
) {
  main();
}
